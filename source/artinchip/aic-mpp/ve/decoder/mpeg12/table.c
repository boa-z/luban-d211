void init_vlcs()
{
    int i, j;
    int code_start, code_end;

    for (int i = 0; i < MAIT_TABLE_SIZE; i++) {
        code_start = mait[i].code << (MACROBLOCK_ADDRESS_INCREMENT_BITS - mait[i].len);
        code_end = code_start | (0xfff >> (VLC_TABLE_BITS - (MACROBLOCK_ADDRESS_INCREMENT_BITS - mait[i].len)));
        for (j = code_start; j <= code_end; j++) {
            macroblock_address_increment_table[j].len = mait[i].len;
            macroblock_address_increment_table[j].value = mait[i].value;
        }
    }

    for (i = 0; i < MTPT_TABLE_SIZE; i++) {
        code_start = mtpt[i].code << (MACROBLOCK_TYPE_BITS - mtpt[i].len);
        code_end = code_start | (0xff >> (8 - (MACROBLOCK_TYPE_BITS - mtpt[i].len)));
        for (j = code_start; j <= code_end; j++) {
            macroblock_type_p_table[j].len = mtpt[i].len;
            macroblock_type_p_table[j].value = mtpt[i].value;
        }
    }

    for (i = 0; i < MTBT_TABLE_SIZE; i++) {
        code_start = mtbt[i].code << (MACROBLOCK_TYPE_BITS - mtbt[i].len);
        code_end = code_start | (0xff >> (8 - (MACROBLOCK_TYPE_BITS - mtbt[i].len)));
        for (j = code_start; j <= code_end; j++) {
            macroblock_type_b_table[j].len = mtbt[i].len;
            macroblock_type_b_table[j].value = mtbt[i].value;
        }
    }

    for (i = 0; i < CBPT_TABLE_SIZE; i++) {
        code_start = cbpt[i].code << (CODED_BLOCK_PATTERN_BITS - cbpt[i].len);
        code_end = code_start | (0xfff >> (VLC_TABLE_BITS - (CODED_BLOCK_PATTERN_BITS - cbpt[i].len)));
        for (j = code_start; j <= code_end; j++) {
            coded_block_pattern_table[j].len = cbpt[i].len;
            coded_block_pattern_table[j].value = cbpt[i].value;
        }
    }

    for (i = 0; i < MCT_TABLE_SIZE; i++) {
        code_start = mct[i].code << (MOTION_CODE_BITS - mct[i].len);
        code_end = code_start | (0xfff >> (VLC_TABLE_BITS - (MOTION_CODE_BITS - mct[i].len)));
        for (j = code_start; j <= code_end; j++) {
            motion_code_table[j].len = mct[i].len;
            motion_code_table[j].value = mct[i].value;
        }
    }

    for (i = 0; i < DDSLT_TABLE_SIZE; i++) {
        code_start = ddslt[i].code << (DCT_DC_SIZE_LUMINANCE_BITS - ddslt[i].len);
        code_end = code_start | (0xfff >> (VLC_TABLE_BITS - (DCT_DC_SIZE_LUMINANCE_BITS - ddslt[i].len)));
        for (j = code_start; j <= code_end; j++) {
            dct_dc_size_luminance_table[j].len = ddslt[i].len;
            dct_dc_size_luminance_table[j].value = ddslt[i].value;
        }
    }
    for (i = 0; i < DDSCT_TABLE_SIZE; i++) {
        code_start = ddsct[i].code << (DCT_DC_SIZE_CHROMINANCE_BITS - ddsct[i].len);
        code_end = code_start | (0xfff >> (VLC_TABLE_BITS - (DCT_DC_SIZE_CHROMINANCE_BITS - ddsct[i].len)));
        for (j = code_start; j <= code_end; j++) {
            dct_dc_size_chrominance_table[j].len = ddsct[i].len;
            dct_dc_size_chrominance_table[j].value = ddsct[i].value;
        }
    }
}
