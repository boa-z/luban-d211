static inline int clamp(int dv, int minval, int maxval)
{
#if (defined(LINUX) && defined(X86))
    int orig = dv;
    __asm__ __volatile__("cmpl %0, %2\n\t"
                         "cmovg %2, %0\n\t"
                         "cmpl %0, %3\n\t"
                         "cmovl %3, %0\n\t"
                         : "=r"(dv)
                         : "0"(dv), "r"(minval), "g"(maxval));
    return dv;
#else
    if (dv < minval)
        dv = minval;
    if (dv > maxval)
        dv = maxval;
    return dv;
#endif
}

