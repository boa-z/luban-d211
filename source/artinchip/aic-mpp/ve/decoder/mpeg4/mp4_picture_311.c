static void x8_loop_filter(uint8_t *ptr, const int a_stride, const int b_stride, int quant)
{
    int i, t;
    int p0, p1, p2, p3, p4, p5, p6, p7, p8, p9;
    int ql = (quant + 10) >> 3;

    for (i = 0; i < 8; i++, ptr += b_stride) {
        p0 = ptr[-5 * a_stride];
        p1 = ptr[-4 * a_stride];
        p2 = ptr[-3 * a_stride];
        p3 = ptr[-2 * a_stride];
        p4 = ptr[-1 * a_stride];
        p5 = ptr[0];
        p6 = ptr[1 * a_stride];
        p7 = ptr[2 * a_stride];
        p8 = ptr[3 * a_stride];
        p9 = ptr[4 * a_stride];

        t = (FFABS(p1 - p2) <= ql) + (FFABS(p2 - p3) <= ql) +
            (FFABS(p3 - p4) <= ql) + (FFABS(p4 - p5) <= ql);
        if (t >
            0) { // You need at least 1 to be able to reach a total score of 6.
            t += (FFABS(p5 - p6) <= ql) + (FFABS(p6 - p7) <= ql) +
                 (FFABS(p7 - p8) <= ql) + (FFABS(p8 - p9) <= ql) +
                 (FFABS(p0 - p1) <= ql);
            if (t >= 6) {
                int min, max;

                min = max = p1;
                min = FFMIN(min, p3);
                max = FFMAX(max, p3);
                min = FFMIN(min, p5);
                max = FFMAX(max, p5);
                min = FFMIN(min, p8);
                max = FFMAX(max, p8);
                if (max - min < 2 * quant) { // early stop
                    min = FFMIN(min, p2);
                    max = FFMAX(max, p2);
                    min = FFMIN(min, p4);
                    max = FFMAX(max, p4);
                    min = FFMIN(min, p6);
                    max = FFMAX(max, p6);
                    min = FFMIN(min, p7);
                    max = FFMAX(max, p7);
                    if (max - min < 2 * quant) {
                        ptr[-2 * a_stride] =
                            (4 * p2 + 3 * p3 + 1 * p7 + 4) >> 3;
                        ptr[-1 * a_stride] =
                            (3 * p2 + 3 * p4 + 2 * p7 + 4) >> 3;
                        ptr[0] = (2 * p2 + 3 * p5 + 3 * p7 + 4) >> 3;
                        ptr[1 * a_stride] = (1 * p2 + 3 * p6 + 4 * p7 + 4) >> 3;
                        continue;
                    };
                }
            }
        }
        {
            int x, x0, x1, x2;
            int m;

            x0 = (2 * p3 - 5 * p4 + 5 * p5 - 2 * p6 + 4) >> 3;
            if (FFABS(x0) < quant) {
                x1 = (2 * p1 - 5 * p2 + 5 * p3 - 2 * p4 + 4) >> 3;
                x2 = (2 * p5 - 5 * p6 + 5 * p7 - 2 * p8 + 4) >> 3;

                x = FFABS(x0) - FFMIN(FFABS(x1), FFABS(x2));
                m = p4 - p5;

                if (x > 0 && (m ^ x0) < 0) {
                    int32_t sign;

                    sign = m >> 31;
                    m = (m ^ sign) - sign; // abs(m)
                    m >>= 1;

                    x = (5 * x) >> 3;

                    if (x > m)
                        x = m;

                    x = (x ^ sign) - sign;

                    ptr[-1 * a_stride] -= x;
                    ptr[0] += x;
                }
            }
        }
    }
}

static void x8_h_loop_filter(uint8_t *src, int stride, int qscale)
{
    x8_loop_filter(src, stride, 1, qscale);
}

static void x8_v_loop_filter(uint8_t *src, int stride, int qscale)
{
    x8_loop_filter(src, 1, stride, qscale);
}

int x8_decode_intra_mb(struct mp4_state *s, mp4_stream_t *ld,
                       intra_x8_context_t *const w, const int chroma)
{
    unsigned int *scantable;
    int final, run, level;
    int ac_mode, dc_mode, est_run, dc_level;
    int pos, n;
    int zeros_only;
    int use_quant_matrix;
    //    int sign;

    if (w->orient >= 12) {
        loge("w->orient >= 12");
        return -1;
    }
    memset(&ld->block[0], 0x00, 64 * sizeof(short));

    if (chroma) {
        dc_mode = 2;
    } else {
        dc_mode = !!w->est_run; // 0,1
    }

    if (x8_get_dc_rlf(ld, w, dc_mode, &dc_level, &final))
        return -1;

    n = 0;
    zeros_only = 0;
    if (!final) { // decode ac
        use_quant_matrix = w->use_quant_matrix;
        if (chroma) {
            ac_mode = 1;
            est_run = 64; // not used
        } else {
            if (w->raw_orient < 3) {
                use_quant_matrix = 0;
            }
            if (w->raw_orient > 4) {
                ac_mode = 0;
                est_run = 64;
            } else {
                if (w->est_run > 1) {
                    ac_mode = 2;
                    est_run = w->est_run;
                } else {
                    ac_mode = 3;
                    est_run = 64;
                }
            }
        }
        x8_select_ac_table(ld, w, ac_mode);
        /*scantable_selector[12]={0,2,0,1,1,1,0,2,2,0,1,2};<-
        -> 10'01' 00'10' 10'00' 01'01' 01'00' 10'00 =>0x928548 */
        // scantable = w->scantable[ (0x928548>>(2*w->orient))&3 ].permutated;
        scantable = wmv1_scantable[0];
        switch ((0x928548 >> (2 * w->orient)) & 3) {
        case 0:
            scantable = wmv1_scantable[0];
            break;
        case 1:
            scantable = wmv1_scantable[2];
            break;
        case 2:
            scantable = wmv1_scantable[3];
            break;
        default:
            break;
        }
        pos = 0;
        do {
            n++;
            if (n >= est_run) {
                ac_mode = 3;
                x8_select_ac_table(ld, w, 3);
            }

            x8_get_ac_rlf(ld, w, ac_mode, &run, &level, &final);

            pos += run + 1;
            if (pos > 63) {
                // this also handles vlc error in x8_get_ac_rlf
                return -1;
            }
            level = (level + 1) *
                    w->dquant; // since the returned level is one_minused, so
                               // here one is plussed first.
            level += w->qsum;

            if (getbits1(ld))
                level = -level;

            if (use_quant_matrix) {
                level = (level * quant_table[pos]) >> 8;
            }
            ld->block[scantable[pos]] = level;
        } while (!final);
    } else {                                                // DC only
        if (w->flat_dc && ((unsigned)(dc_level + 1)) < 3) { //[-1;1]
            int i;
            int divide_quant =
                !chroma ? w->divide_quant_dc_luma : w->divide_quant_dc_chroma;
            int dc_quant = !chroma ? w->quant : w->quant_dc_chroma;

            // original intent dc_level+=predicted_dc/quant; but it got lost
            // somewhere in the rounding
            dc_level += (w->predicted_dc * divide_quant + (1 << 12)) >> 13;

            dsp_x8_put_solidcolor(
                av_clip_uint8((dc_level * dc_quant + 4) >> 3), w->dest[chroma],
                !chroma ? s->coded_picture_width : s->coded_picture_width / 2);

            for (i = 0; i < 64; i++) {
                x8_iqis_out[i] = dc_level * dc_quant;
                x8_idct_out[i] = av_clip_uint8((dc_level * dc_quant + 4) >> 3);
            }
            goto block_placed;
        }
        zeros_only = (dc_level == 0);
    }

    if (!chroma) {
        ld->block[0] = dc_level * w->quant;
    } else {
        ld->block[0] = dc_level * w->quant_dc_chroma;
    }

    // there is !zero_only check in the original, but dc_level check is enough
    if ((unsigned int)(dc_level + 1) >= 3 && (w->edges & 3) != 3) {
        int direction;
        /**
         * ac_comp_direction[orient] = { 0, 3, 3, 1, 1, 0, 0, 0, 2, 2, 2, 1 };<-
         * -> 01'10' 10'10' 00'00' 00'01' 01'11' 11'00 =>0x6A017C
         */
        direction = (0x6A017C >> (w->orient * 2)) & 3;
        if (direction != 3) {
            x8_ac_compensation(&ld->block[0], w, direction,
                               ld->block[0]); // modify block_last[]
        }
    }

    if (w->flat_dc) {
        dsp_x8_put_solidcolor(w->predicted_dc, w->dest[chroma],
                              !chroma ? s->coded_picture_width
                                      : s->coded_picture_width / 2);
    } else {
        w->x8_spatial_compensation[w->orient](
            w->edge_emu_buffer, w->dest[chroma],
            !chroma ? s->coded_picture_width : s->coded_picture_width / 2);
    }

block_placed:

    if (!chroma) {
        x8_update_predictions(s, w, w->orient, n);
    }

    if (s->deblockingflag) {
        // This deblocking must be done, otherwise the picture may be much
        // different.
        unsigned char *ptr = w->dest[chroma];
        int linesize =
            !chroma ? s->coded_picture_width : s->coded_picture_width / 2;

        if (!((w->edges & 2) || (zeros_only && (w->orient | 4) == 4))) {
            x8_h_loop_filter(ptr, linesize, w->quant);
        }
        if (!((w->edges & 1) || (zeros_only && (w->orient | 8) == 8))) {
            x8_v_loop_filter(ptr, linesize, w->quant);
        }
    }
    return 0;
}

