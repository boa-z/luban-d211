static void reconstruct_311(reference_t *ref, int bx, int by)
{
    struct mp4_state *mp4_state = ref->mp4_state;

    int lx, dx, dy;
    int dx_frac, dy_frac;

    lx = mp4_state->coded_picture_width;

    // Luma
    dx = mp4_state->mv[(by + 1) * mp4_state->MV_stride + bx + 1][0].x;
    dy = mp4_state->mv[(by + 1) * mp4_state->MV_stride + bx + 1][0].y;

    dx_frac = dx & 1;
    dy_frac = dy & 1;

    dx = dx >> 1;
    dy = dy >> 1;

    dx += 16 * bx;
    dy += 16 * by;

    dx = clamp(dx, -18, mp4_state->edge_hor_start);
    dy = clamp(dy, -18, mp4_state->edge_ver_start);

    dx = dx * 2 + dx_frac;
    dy = dy * 2 + dy_frac;

    check_and_set_edges(ref, ref->frame_for, dx, dy);

    // Chr

    /* chroma rounding */
    dx = mp4_state->mv[(by + 1) * mp4_state->MV_stride + bx + 1][0].x;
    dy = mp4_state->mv[(by + 1) * mp4_state->MV_stride + bx + 1][0].y;
    if (dx % 4 == 0)
        dx /= 2;
    else if (dx > 0)
        dx = (dx >> 1) | 1;
    else
        dx = -(((-dx) >> 1) | 1);

    if (dy % 4 == 0)
        dy /= 2;
    else if (dy > 0)
        dy = (dy >> 1) | 1;
    else
        dy = -(((-dy) >> 1) | 1);

    ref->fwd_mv_c[0][0] = dx;
    ref->fwd_mv_c[0][1] = dy;

    lx >>= 1;
    dx += 16 * bx;
    dy += 16 * by;
    dx = clamp(dx, -16, mp4_state->edge_hor_start);
    dy = clamp(dy, -16, mp4_state->edge_ver_start);
}

#ifndef FFMIN
#define FFMIN(a, b) ((a) > (b) ? (b) : (a))
#define FFMAX(a, b) ((a) > (b) ? (a) : (b))
#define FFABS(a)    ((a) >= 0 ? (a) : (-(a)))
#endif
static void x8_get_prediction(struct mp4_state *s, intra_x8_context_t *const w)
{
    int a, b, c, i;

    w->edges = 1 * (!s->hdr.mb_xpos);
    w->edges |= 2 * (!s->hdr.mb_ypos);
    w->edges |= 4 * (s->hdr.mb_xpos >= (2 * s->mb_width - 1));

    switch (w->edges & 3) {
    case 0:
        break;
    case 1: // only left edge, vertical prediction
        // take the one from the above block[0][y-1]
        w->est_run = w->prediction_table[!(s->hdr.mb_ypos & 1)] >> 2;
        w->orient = 1;
        return;
    case 2: // only top edge, horizontal prediction
        // take the one from the previous block[x-1][0]
        w->est_run = w->prediction_table[2 * s->hdr.mb_xpos - 2] >> 2;
        w->orient = 2;
        return;
    case 3: // top left edge
        w->est_run = 16;
        w->orient = 0;
        return;
    }

    // no edge cases
    b = w->prediction_table[2 * s->hdr.mb_xpos +
                            !(s->hdr.mb_ypos & 1)]; // block[x  ][y-1]
    a = w->prediction_table[2 * s->hdr.mb_xpos - 2 +
                            (s->hdr.mb_ypos & 1)]; // block[x-1][y  ]
    c = w->prediction_table[2 * s->hdr.mb_xpos - 2 +
                            !(s->hdr.mb_ypos & 1)]; // block[x-1][y-1]

    w->est_run = FFMIN(b, a);
    /* This condition has nothing to do with w->edges, even if it looks
        similar it would trigger if e.g. x=3;y=2;
        I guess somebody wrote something wrong and it became standard. */
    if ((s->hdr.mb_xpos & s->hdr.mb_ypos) != 0)
        w->est_run = FFMIN(c, w->est_run);
    w->est_run >>= 2;

    a &= 3;
    b &= 3;
    c &= 3;

    i = (0xFFEAF4C4 >> (2 * b + 8 * a)) & 3;
    if (i != 3)
        w->orient = i;
    else
        w->orient = (0xFFEAD8 >> (2 * c + 8 * (w->quant > 12))) & 3;
    /*
    lut1[b][a]={
    ->	{0, 1, 0, pad},	//a==0
            {0, 1, X, pad},	//a==1
            {2, 2, 2, pad}}	//a==2
            pad 2   2  2; pad X  1  0; pad 0  1  0 <-
     -> 11 10 '10 10 '11 11'01 00 '11 00'01 00=>0xEAF4C4

      lut2[q>12][c]={
      ->{0,2,1,pad},
            {2,2,2,pad}}
            pad 2  2  2; pad 1  2  0 <-
            -> 11 10'10 10 '11 01'10 00=>0xEAD8
    */
}

static void x8_update_predictions(struct mp4_state *s,
                                  intra_x8_context_t *const w, const int orient,
                                  const int est_run)
{

    w->prediction_table[s->hdr.mb_xpos * 2 + (s->hdr.mb_ypos & 1)] =
        (est_run << 2) + 1 * (orient == 4) + 2 * (orient == 8);
    /**
     * y=2n+0 ->//0 2 4
     * y=2n+1 ->//1 3 5
     */
}

static void x8_get_prediction_chroma(struct mp4_state *s,
                                     intra_x8_context_t *const w)
{
    w->edges = 1 * (!(s->hdr.mb_xpos >> 1));
    w->edges |= 2 * (!(s->hdr.mb_ypos >> 1));
    w->edges |=
        4 * (s->hdr.mb_xpos >=
             (2 * s->mb_width - 1)); // mb_x for chroma would always be odd

    w->raw_orient = 0;
    if (w->edges &
        3) { // lut_co[8]={inv,4,8,8, inv,4,8,8}<- =>{1,1,0,0;1,1,0,0} => 0xCC
        w->chroma_orient = 4 << ((0xCC >> w->edges) & 1);
        return;
    }
    w->chroma_orient = (w->prediction_table[2 * s->hdr.mb_xpos - 2] & 0x03)
                       << 2; // block[x-1][y|1-1)]
}

