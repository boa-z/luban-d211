#define area1 (0)
#define area2 (8)
#define area3 (8 + 8)
#define area4 (8 + 8 + 1)
#define area5 (8 + 8 + 1 + 8)
#define area6 (8 + 8 + 1 + 16)

/**
 Collect statistics and prepare the edge pixels required by the other spatial
 compensation functions.

 * @param src pointer to the beginning of the processed block
 * @param dst pointer to emu_edge, edge pixels are stored the way other
 compensation routines do.
 * @param linesize byte offset between 2 vertical pixels in the source image
 * @param range pointer to the variable where the edge pixel range is to be
 stored (max-min values)
 * @param psum  pointer to the variable where the edge pixel sum is to be stored
 * @param edges Informs this routine that the block is on an image border, so it
 has to interpolate the missing edge pixels. and some of the edge pixels should
 be interpolated, the flag has the following meaning: 1   - mb_x==0 - first
 block in the row, interpolate area #1,#2,#3; 2   - mb_y==0
 - first row, interpolate area #3,#4,#5,#6; note:   1|2 - mb_x==mb_y==0 - first
 block, use 0x80 value for all areas; 4   - mb_x>= (mb_width-1) last block in
 the row, interpolate area #5;
*/
static void x8_setup_spatial_compensation(unsigned char *src,
                                          unsigned char *dst, int linesize,
                                          int *range, int *psum, int edges)
{
    unsigned char *ptr;
    int sum;
    int i;
    int min_pix, max_pix;
    unsigned char c;

    if ((edges & 3) == 3) { // left top edge
        *psum = 0x80 * (8 + 1 + 8 + 2);
        *range = 0;
        memset(dst, 0x80, 16 + 1 + 16 + 8);
        // this triggers flat_dc for sure.
        // flat_dc avoids all (other) prediction modes, but requires dc_level
        // decoding.
        return;
    }

    min_pix = 256;
    max_pix = -1;

    sum = 0;

    if (!(edges & 1)) { //(mb_x!=0)//there is previous block on this row
        ptr = src - 1;  // left column, area 2
        for (i = 7; i >= 0; i--) {
            c = *(ptr - 1); // area1, same mb as area2, no need to check
            dst[area1 + i] = c;
            c = *(ptr);

            sum += c;
            min_pix = FFMIN(min_pix, c);
            max_pix = FFMAX(max_pix, c);
            dst[area2 + i] = c;

            ptr += linesize;
        }
    }

    if (!(edges & 2)) {       //(mb_y!=0)//there is row above
        ptr = src - linesize; // top line
        for (i = 0; i < 8; i++) {
            c = *(ptr + i);
            sum += c;
            min_pix = FFMIN(min_pix, c);
            max_pix = FFMAX(max_pix, c);
        }
        if (edges & 4) {               // last block on the row?
            memset(dst + area5, c, 8); // set with last pixel fr
            memcpy(dst + area4, ptr, 8);
        } else {
            memcpy(dst + area4, ptr, 16); // both area4 and 5
        }
        memcpy(dst + area6, ptr - linesize,
               8); // area6 always present in the above block
    }

    // now calculate the stuff we need
    if (edges & 3) { // mb_x==0 || mb_y==0){
        int avg = (sum + 4) >> 3;
        if (edges & 1) {                         //(mb_x==0) {//implies mb_y!=0
            memset(dst + area1, avg, 8 + 8 + 1); // areas 1,2 and 3 are averaged
        } else {                                 // implies y==0 x!=0
            memset(dst + area3, avg, 1 + 16 + 8); // areas 3, 4,5,6
        }
        sum += avg * 9;
    } else {
        unsigned char c =
            *(src - 1 -
              linesize); // the edge pixel, in the top line and left column
        dst[area3] = c;
        sum += c;
        // edge pixel is not part of min/max
    }

    (*range) = max_pix - min_pix;
    sum += *(dst + area5) + *(dst + area5 + 1);
    *psum = sum;
}

static int x8_get_orient_vlc(struct mp4_state *s, mp4_stream_t *ld,
                             intra_x8_context_t *w)
{
    int table_index;

    if (!w->j_orient_vlc) {
        table_index = getbits(ld, 1 + (w->quant < 13));
        w->j_orient_vlc = j_orient_vlc[w->quant < 13][table_index];
    }

    return get_short_311(ld, w->j_orient_vlc);
}

static void x8_select_ac_table(mp4_stream_t *ld, intra_x8_context_t *w,
                               int mode)
{
    int table_index;

    if (mode >= 4) {
        loge("mode >= 4");
        return;
    }

    if (w->j_ac_vlc[mode])
        return;

    table_index = getbits(ld, 3);
    w->j_ac_vlc[mode] = j_ac_vlc[w->quant < 13][mode >> 1]
                                [table_index]; // 2 modes use same tables

    if (!w->j_ac_vlc[mode]) {
        loge("j_ac_vlc[%d] = NULL", mode);
    }
}

