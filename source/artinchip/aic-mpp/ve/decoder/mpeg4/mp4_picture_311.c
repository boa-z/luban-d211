static int x8_setup_spatial_predictor(struct mp4_state *s, mp4_stream_t *ld,
                                      intra_x8_context_t *const w,
                                      const int chroma)
{
    int range;
    int sum;
    int quant;

    x8_setup_spatial_compensation(w->dest[chroma], w->edge_emu_buffer,
                                  !chroma ? s->coded_picture_width
                                          : s->coded_picture_width / 2,
                                  &range, &sum, w->edges);
    if (chroma) {
        w->orient = w->chroma_orient;
        quant = w->quant_dc_chroma;
    } else {
        quant = w->quant;
    }

    w->flat_dc = 0;
    if (range < quant || range < 3) {
        w->orient = 0;
        if (range <
            3) { // yep you read right, a +-1 idct error may break decoding!
            w->flat_dc = 1;
            sum += 9;
            w->predicted_dc = (sum * 6899) >> 17; //((1<<17)+9)/(8+8+1+2)=6899
        }
    }
    if (chroma)
        return 0;

    if (w->orient >= 3) {
        loge("w->orient >= 3");
        return -1;
    }
    if (range < 2 * w->quant) {
        if ((w->edges & 3) == 0) {
            if (w->orient == 1)
                w->orient = 11;
            if (w->orient == 2)
                w->orient = 10;
        } else {
            w->orient = 0;
        }
        w->raw_orient = 0;
    } else {
        static const unsigned char prediction_table[3][12] = {
            {0, 8, 4, 10, 11, 2, 6, 9, 1, 3, 5, 7},
            {4, 0, 8, 11, 10, 3, 5, 2, 6, 9, 1, 7},
            {8, 0, 4, 10, 11, 1, 7, 2, 6, 9, 3, 5}};
        w->raw_orient = x8_get_orient_vlc(s, ld, w);
        if (w->raw_orient < 0)
            return -1;
        if (w->raw_orient >= 12 || w->orient >= 3) {
            loge("param error [%d / %d]", w->raw_orient, w->orient);
        }
        w->orient = prediction_table[w->orient][w->raw_orient];
    }

    return 0;
}
static void x8_ac_compensation(short *block, intra_x8_context_t *w, int direction, int dc_level)
{
    int t;

#define B(x, y) block[(x) + (y) * 8]
#define T(x)    ((x) * dc_level + 0x8000) >> 16;

    switch (direction) {
    case 0:
        t = T(3811); // h
        B(1, 0) -= t;
        B(0, 1) -= t;

        t = T(487); // e
        B(2, 0) -= t;
        B(0, 2) -= t;

        t = T(506); // f
        B(3, 0) -= t;
        B(0, 3) -= t;

        t = T(135); // c
        B(4, 0) -= t;
        B(0, 4) -= t;
        B(2, 1) += t;
        B(1, 2) += t;
        B(3, 1) += t;
        B(1, 3) += t;

        t = T(173); // d
        B(5, 0) -= t;
        B(0, 5) -= t;

        t = T(61); // b
        B(6, 0) -= t;
        B(0, 6) -= t;
        B(5, 1) += t;
        B(1, 5) += t;

        t = T(42); // a
        B(7, 0) -= t;
        B(0, 7) -= t;
        B(4, 1) += t;
        B(1, 4) += t;
        B(4, 4) += t;

        t = T(1084); // g
        B(1, 1) += t;

        break;
    case 1:
        B(0, 1) -= T(6269);
        B(0, 3) -= T(708);
        B(0, 5) -= T(172);
        B(0, 7) -= T(73);

        break;
    case 2:
        B(1, 0) -= T(6269);
        B(3, 0) -= T(708);
        B(5, 0) -= T(172);
        B(7, 0) -= T(73);

        break;
    }
#undef B
#undef T
}

